import ReactMarkdown, { defaultUrlTransform } from "react-markdown";
import { useContext } from "react";
import { RichTextPolicy } from "./RichTextPolicy";
import remarkGfm from "remark-gfm";
import remarkMath from "remark-math";
import "katex/dist/katex.min.css";
import { RevealArtifactButton } from "./ArtifactActions";
import {
  artifactNameFromHref,
  artifactNameFromPath,
  remarkArtifactLinks,
} from "./artifactLinks";
import { normalizeMathDelimiters, rehypeMath } from "./markdownMath";
import { openArtifact } from "./workbenchEvents";

const SLUG = /\b(?:clm|prf|ref)_[0-9a-f]{4,}\b/g;
const SLUG_ONLY = /^(?:clm|prf|ref)_[0-9a-f]{4,}$/;

/** React Markdown rejects non-web schemes by default. Preserve `file:` and
 * `sandbox:` only when they identify a project artifact; the anchor renderer
 * intercepts those links before the browser or desktop shell navigates. */
function urlTransform(url: string): string {
  return artifactNameFromPath(url) ? url : defaultUrlTransform(url);
}

const shortSlug = (slug: string) =>
  slug.length > 14 ? `${slug.slice(0, 12)}…` : slug;

/** Turn bare slugs into markdown links, skipping code and math segments
 *  (backticked slugs are handled by the code renderer instead). */
function linkifySlugs(text: string): string {
  const parts = text.split(
    /(```[\s\S]*?```|`[^`]*`|\$\$[\s\S]*?\$\$|\$[^$\n]*\$)/g,
  );
  return parts
    .map((part, i) => {
      if (i % 2 === 1) return part;
      return part.replace(SLUG, (slug) => `[${shortSlug(slug)}](#lgr-${slug})`);
    })
    .join("");
}

function LedgerAnchor(props: {
  href?: string;
  children?: React.ReactNode;
}) {
  const policy = useContext(RichTextPolicy);
  const href = props.href ?? "";
  if (href.startsWith("#lgr-")) {
    const slug = href.slice(5);
    return (
      <a
        className="ledger-link"
        href={href}
        onClick={(event) => {
          event.preventDefault();
          policy.onOpenLedger(slug);
        }}
      >
        {props.children}
      </a>
    );
  }
  const artifact = artifactNameFromHref(href);
  if (artifact) {
    if (!policy.allowArtifacts) return <span>{props.children}</span>;
    return (
      <span className="artifact-inline-reference">
        <a
          className="ledger-link"
          href={href}
          title={`artifacts/${artifact}`}
          onClick={(event) => {
            event.preventDefault();
            openArtifact(artifact);
          }}
        >
          {props.children}
        </a>
        <RevealArtifactButton name={artifact} compact />
      </span>
    );
  }
  return (
    <a href={href} target="_blank" rel="noreferrer">
      {props.children}
    </a>
  );
}

function CodeOrSlug(props: { children?: React.ReactNode; className?: string }) {
  const policy = useContext(RichTextPolicy);
  const child = Array.isArray(props.children) ? props.children[0] : props.children;
  if (typeof child === "string" && SLUG_ONLY.test(child.trim())) {
    const slug = child.trim();
    return (
      <code
        className="ledger-link"
        title={slug}
        onClick={() => policy.onOpenLedger(slug)}
      >
        {shortSlug(slug)}
      </code>
    );
  }
  const artifact =
    typeof child === "string" ? artifactNameFromPath(child.trim()) : null;
  if (artifact) {
    if (!policy.allowArtifacts) return <code>{props.children}</code>;
    return (
      <span className="artifact-inline-reference">
        <code
          className="ledger-link"
          title={`artifacts/${artifact}`}
          onClick={() => openArtifact(artifact)}
        >
          {props.children}
        </code>
        <RevealArtifactButton name={artifact} compact />
      </span>
    );
  }
  return <code className={props.className}>{props.children}</code>;
}

const COMPONENTS = { a: LedgerAnchor, code: CodeOrSlug };

// KaTeX emits an accessible MathML tree alongside its visual HTML. Unwrapping
// that tree into plain text exposes TeX/Unicode twice and destroys accessibility.
// These elements are generated by rehype-katex; author HTML remains disabled.
const INLINE_ELEMENTS = [
  "p", "em", "strong", "code", "span", "a",
  "math", "semantics", "annotation", "mrow", "mi", "mn", "mo", "mtext", "mspace",
  "mstyle", "mfrac", "msqrt", "mroot", "msub", "msup", "msubsup", "munder", "mover",
  "munderover", "mtable", "mtr", "mtd", "menclose", "mpadded", "mphantom", "none",
  "svg", "path", "line",
];

export function RichTextRenderer({
  inline,
  text,
}: {
  inline: boolean;
  text: string;
}) {
  const policy = useContext(RichTextPolicy);
  const content = (
    <ReactMarkdown
      remarkPlugins={inline
        ? [remarkMath, remarkArtifactLinks]
        : [remarkGfm, remarkMath, remarkArtifactLinks]}
      rehypePlugins={[rehypeMath]}
      urlTransform={urlTransform}
      allowedElements={inline
        ? INLINE_ELEMENTS
        : undefined}
      unwrapDisallowed={inline || undefined}
      components={policy.allowImages ? COMPONENTS : { ...COMPONENTS, img: () => null }}
    >
      {linkifySlugs(normalizeMathDelimiters(text))}
    </ReactMarkdown>
  );
  return inline
    ? <span className="md">{content}</span>
    : <div className="md">{content}</div>;
}
